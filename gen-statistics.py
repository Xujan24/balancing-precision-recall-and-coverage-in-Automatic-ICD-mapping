"""
Script to generate the statistics (precision, recall, f1-score, mapping coverage, average candidate set size per source code).
For macro-averaged statistics, use `--use-macr` flag.
For generating statistic using the maps generated by blocking-and-matching framework, use the flag `--matching`
"""

import argparse
import os
import pandas as pd
from utils.helpers import load_from_pkl, parse_string_as_list
from config import ALLOWED_METHODS_DICT, MAPPING_PAIRS


if __name__=='__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('ch', type=str, help='Chapter (e.g. inf for Intestinal Infectious Diseases)')
    parser.add_argument('method', type=str, help='Method to generate maps - threshold, baseline')
    parser.add_argument('--th', type=float, default=0.85, help='Threshold value used to generate the map; Default value 0.85')
    parser.add_argument('--k', type=int, default=3, help='Value for Top-K nearest target codes')
    parser.add_argument('--use-macro', action='store_true', default=False, help='Micro or Macro averaging; Default Micro.')
    parser.add_argument('--matching', action='store_true', default=False, help='Calculate the matching statistics; Default False')
    args = parser.parse_args()

    print(f'Method: {"Macro" if args.use_macro else "Micro"}')
    print('[SRC-to-TGT\t| Avg. Precision\t| Avg. Recall\t| Avg. F1 Score\t| coverage \t| Avg # maps]\n')

    for test_set in MAPPING_PAIRS:
        ## load target csv files to get a list of valid target codes
        tgt_df = pd.read_csv(os.path.join('./data/icd', f'{test_set["tgt"]}_{args.ch}.csv'), dtype=str)
        valid_tgt_codes = tgt_df['code'].tolist()
        del tgt_df

        pred_map_path = './out/matching/' if args.matching else './out/blocking/'
        pred_map_path = f'{pred_map_path}/{args.ch}/{ALLOWED_METHODS_DICT.get(args.method)}'
        if args.method == 'th':
            pred_map_path = f'{pred_map_path}/{str(args.th)}'
        
        if args.method in ['topk', 'default', 'prank']:
            pred_map_path = f'{pred_map_path}/{str(args.k)}'

        pred_map = load_from_pkl(f'{pred_map_path}/{test_set["src"]}_{test_set["tgt"]}.pkl')
        gt_dict = load_from_pkl(f'./data/gt/{test_set["src"]}_{test_set["tgt"]}.pkl')

        ## lets filter out the target codes that are not in the valid _tgt_codes
        ## Note: we don't exclude the entire row, but only the invalid target codes and keep the rest
        ## However, if all target codes are invalid then, we remove the entire row
        fltr_gt_dict = {}
        for k, v in gt_dict.items():
            fltr_gt = []

            for c in v:
                if c in valid_tgt_codes:
                    fltr_gt.append(c)
            if len(fltr_gt) <= 0:
                continue
            fltr_gt_dict[k] = fltr_gt

        del gt_dict, valid_tgt_codes

        ## based on the avg. method, we keep track of the corresponding statistics.
        if args.use_macro:
            precisions = []
            recalls = []
        else:
            TP = 0
            FP = 0
            FN = 0

        total_valid_cases = 0   # not all predicted maps are valid; some don't exists in the ground truth
        total_pred_maps = 0     # count for the # of cases where maps were generated. Some won't have a map, for example using threshold
        total_maps_per_item = 0 # count of # of maps per source item

        for k, v in pred_map.items():
            v = parse_string_as_list(v) if isinstance(v, str) else v
            gt = fltr_gt_dict.get(k)

            if not gt:
                continue
            
            total_valid_cases +=1

            if len(v) > 0:
                total_pred_maps += 1
                
                total_maps_per_item += len(v)

                tp = len(set(v) & set(gt))
                fp = len(set(v) - set(gt))
                fn = len(set(gt) - set(v))

            else:
                tp = 0
                fp = 0
                fn = len(set(gt))
            
            if args.use_macro:
                    if tp == 0:
                        precisions.append(0)
                        recalls.append(0)
                    else:
                        precisions.append(round(tp/(tp+fp), 2))
                        recalls.append(round(tp/(tp+fn), 2))
            else:
                TP += tp
                FP += fp
                FN += fn
            
        if args.use_macro:
            precision = round(sum(precisions)/len(precisions), 2)
            recall = round(sum(recalls)/len(recalls), 2)
        else:
            precision = round(TP/(TP+FP), 2)
            recall = round(TP/(TP+FN), 2)
        f1 = 2 * precision*recall/(precision+recall)
        print(f'[{test_set["src"]}-{test_set["tgt"]}\t|{round(precision, 2)} & {round(recall, 2)} & {round(f1, 2)} & {round(total_pred_maps/total_valid_cases, 2)} & {round(total_maps_per_item/total_pred_maps, 2)}]')