"""
Script to generate the statistics for cases where at least one of the predicted target code is a valid parent of the ground-truth code.
We use the maps generated by the blocking-and-matching framework, using default block size (i.e. K=5).
"""

from typing import Dict
import pandas as pd
from utils.helpers import load_from_pkl,filter_nan, parse_string_as_list
from config import MAPPING_PAIRS, CHAPTERS

def get_nested_codes(df: pd.DataFrame, exclude_parent: bool = True) -> Dict[str, Dict[str, str]]:
    """returns a dict with all the codes that has child codes.
    
    Keyword arguments:
    df -- pandas.DataFrame object
    Return: a Dict object with key as the ICD code and child code and code descriptions as values.
    """
    
    ## get the codes that has child codes
    parent_ids = set()
    for code in df['code']:
        if any(_code.startswith(code) and code != _code for _code in df['code']):
            parent_ids.add(code)
    
    ## get the child codes to the corresponding parent codes
    nested_dict = {}
    for parent in parent_ids:
        children = df[df['code'].str.startswith(parent)]
        if exclude_parent:
            children = children[children['code'] != parent]
        children = filter_nan(children.values.tolist())
        nested_dict[parent] = {
            row[0]: row[1] for row in children
        }
    
    return nested_dict


if __name__ == "__main__":
    for pair in MAPPING_PAIRS:
        src = pair['src']
        tgt = pair['tgt']

        for ch in CHAPTERS:
            tgt_df = pd.read_csv(f'./data/icd/{tgt}_{ch}.csv', dtype=str)
            valid_tgt_codes = tgt_df['code'].tolist()
            parent_codes = get_nested_codes(tgt_df)
            del tgt_df

            pred_maps = load_from_pkl(f'./out/matching/{ch}/Default/5/{src}_{tgt}.pkl')

            gt_dict = load_from_pkl(f'./data/gt/{src}_{tgt}.pkl')
            ## lets filter out the target codes that are not in the valid _tgt_codes
            ## Note: we don't exclude the entire row, but only the invalid target codes and keep the rest
            ## However, if all target codes are invalid then, we remove the entire row
            fltr_gt_dict = {}
            for k, v in gt_dict.items():
                fltr_gt = []

                for c in v:
                    if c in valid_tgt_codes:
                        fltr_gt.append(c)
                if len(fltr_gt) <= 0:
                    continue
                fltr_gt_dict[k] = fltr_gt

            del gt_dict

            count_total_parent = 0
            count_correct = 0
            for k, v in pred_maps.items():
                v = parse_string_as_list(v) if isinstance(v, str) else v
                gt = fltr_gt_dict.get(k)

                if len(v) == 0:
                    continue

                if gt is None or len(set(gt).intersection(set(valid_tgt_codes))) == 0:
                    continue

                if any(a.startswith(b) and a != b for a in gt for b in list(parent_codes.keys())):
                    count_total_parent += 1
                    if any(x.startswith(y) and x!=y for x in gt for y in v):
                        count_correct += 1

            if count_total_parent == 0:
                print(f'{src}→{tgt} [{ch}]: {0.00}% (-)')
                continue
            print(f'{src}→{tgt} [{ch}]: {round(count_correct/count_total_parent*100, 2)}% ({count_total_parent})')